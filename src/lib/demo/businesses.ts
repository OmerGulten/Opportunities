function rv(rating: number, when: Recency, hasOwnerReply: boolean | null): PlaceReviewSample {
  return { rating, ...RECENCY[when], hasOwnerReply };
}

interface Seed {
  slug: string;
  name: string;
  category: DemoCategoryKey;
  primaryType: string;
  types: string[];
  lat: number;
  lng: number;
  address: string;
  rating: number;
  ratingCount: number;
  phone?: string;
  hours?: PlaceOpeningHours | null;
  photos: number;
  reviews: PlaceReviewSample[];
  website?: { host: string; profile: DemoWebsiteProfile; scheme?: "http" | "https" };
  instagram?: string;
  priceLevel?: string;
  keywords?: string[];
}

function build(seed: Seed): DemoBusiness {
  const phones = seed.phone ? phone(seed.phone) : { phoneNational: null, phoneInternational: null };
  const websiteUri = seed.website ? `${seed.website.scheme ?? "https"}://${seed.website.host}.${DEMO_WEBSITE_DOMAIN}` : null;
  return {
    provider: "demo",
    providerPlaceId: `demo_${seed.slug}`,
    displayName: seed.name,
    formattedAddress: `${seed.address}, 34710 Kadıköy/İstanbul, Türkiye`,
    location: { lat: seed.lat, lng: seed.lng },
    primaryType: seed.primaryType,
    types: Array.from(new Set([seed.primaryType, ...seed.types, "point_of_interest", "establishment"])),
    businessStatus: "OPERATIONAL",
    city: "İstanbul",
    district: "Kadıköy",
    countryCode: "TR",
    rating: seed.rating,
    userRatingCount: seed.ratingCount,
    websiteUri,
    ...phones,
    // Real Google Maps URL pointing at the fictional coordinates; safe to open.
    googleMapsUri: `https://www.google.com/maps/search/?api=1&query=${seed.lat},${seed.lng}`,
    openingHours: seed.hours ?? null,
    photoCount: seed.photos,
    priceLevel: seed.priceLevel ?? null,
    reviewSample: seed.reviews,
    socialProfiles: seed.instagram ? [{ platform: "instagram", url: `https://www.instagram.com/${seed.instagram}` }] : null,
    categoryKey: seed.category,
    websiteProfile: seed.website?.profile ?? null,
    keywords: seed.keywords ?? [],
  };
}

