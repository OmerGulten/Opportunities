export const DEMO_CENTER = { lat: 40.9903, lng: 29.029 } as const;
export const DEMO_WEBSITE_DOMAIN = "demo-sites.example";

const WEEKDAYS_TR = ["Pazartesi", "Salı", "Çarşamba", "Perşembe", "Cuma", "Cumartesi", "Pazar"] as const;
type Weekday = (typeof WEEKDAYS_TR)[number];

interface HoursSpec {
  open: string;
  close: string;
  closed?: Weekday[];
  /** Per-day overrides, e.g. shorter Saturday. */
  overrides?: Partial<Record<Weekday, string>>;
}

function hours(spec: HoursSpec): PlaceOpeningHours {
  const closed = new Set(spec.closed ?? []);
  const weekdayDescriptions = WEEKDAYS_TR.map((day) => {
    if (closed.has(day)) return `${day}: Kapalı`;
    const range = spec.overrides?.[day] ?? `${spec.open}–${spec.close}`;
    return `${day}: ${range}`;
  });
  return { weekdayDescriptions, periodsCount: WEEKDAYS_TR.length - closed.size };
}

function allDay(): PlaceOpeningHours {
  return { weekdayDescriptions: WEEKDAYS_TR.map((d) => `${d}: 24 saat açık`), periodsCount: 1 };
}

/** "216 336 41 18" -> national "(0216) 336 41 18", international "+90 216 336 41 18". */
function phone(local: string): { phoneNational: string; phoneInternational: string } {
  const [area, ...rest] = local.split(" ");
  return { phoneNational: `(0${area}) ${rest.join(" ")}`, phoneInternational: `+90 ${area} ${rest.join(" ")}` };
}

